import os
import joblib
import pandas as pd
import streamlit as st

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE_DIR, "models", "diabetes_model.joblib")
DATA_PATH = os.path.join(BASE_DIR, "data", "diabetes.csv")

FEATURES = [
    "Pregnancies", "Glucose", "BloodPressure", "SkinThickness",
    "Insulin", "BMI", "DiabetesPedigreeFunction", "Age"
]

st.set_page_config(page_title="Diabetes Risk Prediction", page_icon="🩺", layout="wide")
st.title("🩺 Diabetes Risk Prediction")
st.write("Enter the health measurements below to receive a machine-learning demonstration prediction.")

@st.cache_resource
def load_model():
    if not os.path.exists(MODEL_PATH):
        return None
    return joblib.load(MODEL_PATH)

model = load_model()
if model is None:
    st.warning("The model file is not available yet. Run `python train_model.py` in the project folder, then refresh this page.")
    st.stop()

st.sidebar.header("About this project")
st.sidebar.info("Educational machine-learning demo using a synthetic dataset. It is not a medical test or diagnosis.")

with st.form("prediction_form"):
    left, right = st.columns(2)
    with left:
        pregnancies = st.number_input("Pregnancies", min_value=0, max_value=20, value=1, step=1)
        glucose = st.number_input("Glucose (mg/dL)", min_value=0.0, max_value=250.0, value=120.0)
        blood_pressure = st.number_input("Blood Pressure (mmHg)", min_value=0.0, max_value=150.0, value=70.0)
        skin = st.number_input("Skin Thickness (mm)", min_value=0.0, max_value=100.0, value=20.0)
    with right:
        insulin = st.number_input("Insulin (mu U/ml)", min_value=0.0, max_value=900.0, value=80.0)
        bmi = st.number_input("BMI", min_value=0.0, max_value=80.0, value=28.0)
        dpf = st.number_input("Diabetes Pedigree Function", min_value=0.0, max_value=3.0, value=0.5)
        age = st.number_input("Age (years)", min_value=1, max_value=120, value=30, step=1)
    submitted = st.form_submit_button("Predict risk")

if submitted:
    row = pd.DataFrame([{
        "Pregnancies": pregnancies, "Glucose": glucose,
        "BloodPressure": blood_pressure, "SkinThickness": skin,
        "Insulin": insulin, "BMI": bmi,
        "DiabetesPedigreeFunction": dpf, "Age": age
    }], columns=FEATURES)
    prediction = int(model.predict(row)[0])
    probability = float(model.predict_proba(row)[0][1])
    st.subheader("Prediction result")
    st.metric("Model-estimated probability", "{:.1f}%".format(probability * 100))
    st.progress(min(max(probability, 0.0), 1.0))
    if prediction == 1:
        st.error("The model classifies this input as: Higher-risk class")
    else:
        st.success("The model classifies this input as: Lower-risk class")
    st.caption("This result is generated by a model trained on synthetic demonstration data. Do not use it for diagnosis or treatment. Consult a qualified healthcare professional.")

st.divider()
st.subheader("Dataset preview")
data = pd.read_csv(DATA_PATH)
st.dataframe(data.head(10), use_container_width=True)
st.caption("The included CSV is synthetic (artificially generated), not real patient records.")
